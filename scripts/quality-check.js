/*
 * ------------------------------------------------------------
 * SECTION 11
 * ARTIFICIAL OPENING
 * ------------------------------------------------------------
 */

function checkOpening(
  generated,
  errors,
  warnings
) {
  if (!isObject(generated.lesson)) {
    return;
  }

  const opening =
    normalize(
      generated.lesson.opening
    );

  const weakOpenings = [
    "ఈ రోజు మనం",
    "ఈ పాఠంలో మనం",
    "ఈ రోజు మనం తెలుసుకుందాం",
    "ఈ పాఠంలో తెలుసుకుందాం",
    "ఈ రోజు మనం నేర్చుకోబోతున్నాం",
    "మనము ఈ రోజు"
  ];

  for (const phrase of weakOpenings) {
    if (
      opening.startsWith(
        normalize(phrase)
      )
    ) {
      addWarning(
        warnings,
        `Opening uses a generic classroom-style beginning: "${phrase}"`
      );

      break;
    }
  }

  /*
   * Opening should not be just one tiny sentence.
   */

  if (opening.length < 80) {
    addError(
      errors,
      "Opening is too short to establish the human importance of the topic."
    );
  }
}


/*
 * ------------------------------------------------------------
 * SECTION 12
 * HUMAN RELEVANCE
 * ------------------------------------------------------------
 */

function checkHumanRelevance(
  generated,
  errors,
  warnings
) {
  if (!isObject(generated.lesson)) {
    return;
  }

  const relevantFields = [
    "why_it_matters",
    "real_life_example",
    "what_it_means_for_me",
    "takeaway"
  ];

  const combined =
    relevantFields
      .map(field =>
        generated.lesson[field] || ""
      )
      .join("\n");

  const humanTerms = [
    "మన",
    "ప్రజ",
    "పౌర",
    "జీవితం",
    "రోజువారీ",
    "సమాజం",
    "కుటుంబం",
    "వ్యక్తి",
    "హక్కు",
    "బాధ్యత"
  ];

  const matches =
    humanTerms.filter(
      term =>
        combined.includes(term)
    ).length;

  if (matches < 2) {
    addWarning(
      warnings,
      "Human-life relevance appears weak."
    );
  }
}


/*
 * ------------------------------------------------------------
 * SECTION 13
 * PARAGRAPH READABILITY
 * ------------------------------------------------------------
 */

function checkReadability(
  generated,
  warnings
) {
  if (!isObject(generated.lesson)) {
    return;
  }

  for (const field of LESSON_FIELDS) {
    const text =
      generated.lesson[field];

    if (
      typeof text !== "string" ||
      !text.trim()
    ) {
      continue;
    }

    const sentences =
      splitSentences(text);

    if (sentences.length === 0) {
      continue;
    }

    /*
     * Warn about extremely long sentences.
     *
     * This is a warning rather than a hard failure because
     * Telugu sentence length varies naturally.
     */

    const longSentences =
      sentences.filter(
        sentence =>
          sentence.length > 350
      );

    if (
      longSentences.length >= 2
    ) {
      addWarning(
        warnings,
        `lesson.${field} contains several very long sentences.`
      );
    }
  }
}


