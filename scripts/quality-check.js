/*
 * ------------------------------------------------------------
 * SECTION 16
 * QUALITY SCORE
 * ------------------------------------------------------------
 *
 * Score is supplementary.
 *
 * A lesson fails based on hard errors first.
 * The score helps us understand how strong a passing lesson is.
 * ------------------------------------------------------------
 */

function calculateScore(
  generated
) {
  if (
    !generated ||
    !isObject(generated.lesson)
  ) {
    return 0;
  }

  let score = 100;

  const combined =
    LESSON_FIELDS
      .map(field =>
        generated.lesson[field] || ""
      )
      .join("\n");

  const totalLength =
    combined.trim().length;

  if (totalLength < 1200) {
    score -= 8;
  }

  if (totalLength > 25000) {
    score -= 5;
  }

  const ratio =
    teluguRatio(combined);

  if (ratio < 0.60) {
    score -= 10;
  }

  if (ratio < 0.50) {
    score -= 10;
  }

  const duplicates =
    getDuplicateSentences(combined);

  score -=
    duplicates.length * 8;

  let genericCount = 0;

  for (const phrase of GENERIC_PHRASES) {
    genericCount +=
      countOccurrences(
        combined,
        phrase
      );
  }

  score -=
    Math.min(
      genericCount * 3,
      15
    );

  return Math.max(
    0,
    Math.min(100, score)
  );
}


/*
 * ------------------------------------------------------------
 * MAIN QUALITY CHECK
 * ------------------------------------------------------------
 */

function checkQuality({
  generated,
  syllabus
}) {
  const errors = [];
  const warnings = [];

  if (!isObject(generated)) {
    return {
      valid: false,
      score: 0,
      errors: [
        "Generated lesson must be an object."
      ],
      warnings: []
    };
  }

  if (!isObject(syllabus)) {
    return {
      valid: false,
      score: 0,
      errors: [
        "Syllabus entry is missing or invalid."
      ],
      warnings: []
    };
  }

  checkLessonStructure(
    generated,
    errors,
    warnings
  );

  checkOverallLength(
    generated,
    errors,
    warnings
  );

  checkTelugu(
    generated,
    errors,
    warnings
  );

  checkRealLifeExample(
    generated,
    errors,
    warnings
  );

  checkMisunderstanding(
    generated,
    errors,
    warnings
  );

  checkTakeaway(
    generated,
    errors,
    warnings
  );

  checkRepetition(
    generated,
    errors,
    warnings
  );

  checkGenericContent(
    generated,
    errors,
    warnings
  );

  checkExamStyle(
    generated,
    errors,
    warnings
  );

  checkAIMeta(
    generated,
    errors
  );

  checkOpening(
    generated,
    errors,
    warnings
  );

  checkHumanRelevance(
    generated,
    errors,
    warnings
  );

  checkReadability(
    generated,
    warnings
  );

  checkComparison(
    generated,
    errors,
    warnings
  );

  checkPersonalMeaning(
    generated,
    errors
  );

  const score =
    calculateScore(
      generated
    );

  /*
   * A score below 70 means the lesson is not good enough
   * even if the structural validator happened to pass.
   */

  if (score < 70) {
    addError(
      errors,
      `Editorial quality score is too low: ${score}/100.`
    );
  }

  return {
    valid: errors.length === 0,
    score,
    errors,
    warnings
  };
}


/*
 * ------------------------------------------------------------
 * CLI MODE
 * ------------------------------------------------------------
 *
 * Usage:
 *
 * node scripts/quality-check.js data/day-001.json
 * ------------------------------------------------------------
 */

function loadJson(filePath) {
  const absolutePath =
    path.resolve(filePath);

  if (!fs.existsSync(absolutePath)) {
    throw new Error(
      `File not found: ${absolutePath}`
    );
  }

  const text =
    fs.readFileSync(
      absolutePath,
      "utf8"
    );

  try {
    return JSON.parse(text);
  } catch (error) {
    throw new Error(
      `Invalid JSON in ${absolutePath}: ${error.message}`
    );
  }
}


function findSyllabusEntry(
  syllabusFile,
  day
) {
  if (Array.isArray(syllabusFile)) {
    return syllabusFile.find(
      item =>
        Number(item.day) === day
    );
  }

  if (
    isObject(syllabusFile) &&
    Array.isArray(syllabusFile.days)
  ) {
    return syllabusFile.days.find(
      item =>
        Number(item.day) === day
    );
  }

  return null;
}


async function runCli() {
  const generatedPath =
    process.argv[2];

  if (!generatedPath) {
    console.error(
      "Usage: node scripts/quality-check.js <generated-json>"
    );

    process.exit(1);
  }

  const generated =
    loadJson(generatedPath);

  const day =
    Number(generated.day);

  if (
    !Number.isInteger(day) ||
    day < 1 ||
    day > 365
  ) {
    console.error(
      "Invalid day in generated lesson."
    );

    process.exit(1);
  }

  const syllabusPath =
    path.resolve(
      __dirname,
      "..",
      "data",
      "syllabus.json"
    );

  const syllabusFile =
    loadJson(syllabusPath);

  const syllabus =
    findSyllabusEntry(
      syllabusFile,
      day
    );

  if (!syllabus) {
    console.error(
      `Could not find day ${day} in syllabus.json`
    );

    process.exit(1);
  }

  const result =
    checkQuality({
      generated,
      syllabus
    });

  console.log(
    "\n=========================================="
  );

  console.log(
    `CONSTITUTION 365 QUALITY CHECK — DAY ${day}`
  );

  console.log(
    "==========================================\n"
  );

  console.log(
    `QUALITY SCORE: ${result.score}/100`
  );

  console.log(
    `STATUS: ${result.valid ? "PASS" : "FAIL"}`
  );

  if (result.errors.length > 0) {
    console.log("\nERRORS:");

    for (const error of result.errors) {
      console.log(`  ✗ ${error}`);
    }
  }

  if (result.warnings.length > 0) {
    console.log("\nWARNINGS:");

    for (const warning of result.warnings) {
      console.log(`  ! ${warning}`);
    }
  }

  console.log("");

  if (!result.valid) {
    process.exit(1);
  }
}


/*
 * ------------------------------------------------------------
 * EXPORTS
 * ------------------------------------------------------------
 */

module.exports = {
  checkQuality,
  calculateScore
};


if (require.main === module) {
  runCli().catch(error => {
    console.error(
      `\nQUALITY CHECK ERROR: ${error.message}`
    );

    process.exit(1);
  });
}
