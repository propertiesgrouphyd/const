"use strict";

/*
 * CONSTITUTION 365
 * Editorial Quality Checker
 *
 * Purpose:
 * Check whether a generated lesson is:
 * - clear
 * - sufficiently detailed
 * - genuinely useful
 * - naturally written in Telugu
 * - non-repetitive
 * - example-driven
 * - appropriate for ordinary people
 * - free from obvious exam-note / AI-output patterns
 *
 * IMPORTANT:
 * This is a deterministic quality gate.
 *
 * It does NOT replace human/editorial review.
 * It identifies obvious weak generations so that the pipeline
 * can automatically regenerate them.
 */

const {
  LESSON_FIELDS
} = require("./validate-day");


/*
 * ------------------------------------------------------------
 * CONFIGURATION
 * ------------------------------------------------------------
 */

const MIN_TOTAL_CHARACTERS = 900;
const MAX_TOTAL_CHARACTERS = 30000;

const MIN_FIELD_CHARACTERS = {
  opening: 80,
  explanation: 180,
  why_it_matters: 100,
  how_it_works: 100,
  real_life_example: 100,
  simple_comparison: 60,
  common_misunderstanding: 60,
  what_it_means_for_me: 80,
  takeaway: 50
};

const MIN_TELUGU_RATIO = 0.45;

const MAX_REPEATED_SENTENCE_COUNT = 1;

const MAX_GENERIC_PHRASE_COUNT = 2;


