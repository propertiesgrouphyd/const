/*
 * ------------------------------------------------------------
 * SECTION 7
 * REPETITION
 * ------------------------------------------------------------
 */

function checkRepetition(
  generated,
  errors,
  warnings
) {
  if (!isObject(generated.lesson)) {
    return;
  }

  const combined =
    LESSON_FIELDS
      .map(field =>
        generated.lesson[field] || ""
      )
      .join("\n");

  const duplicates =
    getDuplicateSentences(
      combined
    );

  if (duplicates.length > 0) {
    for (const item of duplicates.slice(0, 5)) {
      addError(
        errors,
        `Repeated sentence detected ${item.count} times: "${item.sentence}"`
      );
    }
  }

  /*
   * Check repeated phrases across sections.
   */

  const normalizedFields =
    LESSON_FIELDS.map(
      field => ({
        field,
        text: normalize(
          generated.lesson[field]
        )
      })
    );

  for (
    let i = 0;
    i < normalizedFields.length;
    i++
  ) {
    for (
      let j = i + 1;
      j < normalizedFields.length;
      j++
    ) {
      const first =
        normalizedFields[i];

      const second =
        normalizedFields[j];

      if (
        first.text.length > 100 &&
        second.text.length > 100 &&
        (
          first.text.includes(
            second.text
          ) ||
          second.text.includes(
            first.text
          )
        )
      ) {
        addWarning(
          warnings,
          `Possible repeated content between lesson.${first.field} and lesson.${second.field}.`
        );
      }
    }
  }
}


/*
 * ------------------------------------------------------------
 * SECTION 8
 * GENERIC CONTENT
 * ------------------------------------------------------------
 */

function checkGenericContent(
  generated,
  errors,
  warnings
) {
  if (!isObject(generated.lesson)) {
    return;
  }

  const combined =
    LESSON_FIELDS
      .map(field =>
        generated.lesson[field] || ""
      )
      .join("\n");

  let genericCount = 0;

  for (const phrase of GENERIC_PHRASES) {
    genericCount +=
      countOccurrences(
        combined,
        phrase
      );
  }

  if (
    genericCount >
    MAX_GENERIC_PHRASE_COUNT
  ) {
    addWarning(
      warnings,
      `Generic filler-style phrases appear frequently (${genericCount}).`
    );
  }

  /*
   * If the lesson is dominated by generic language,
   * reject it.
   */

  if (
    genericCount >= 6
  ) {
    addError(
      errors,
      "Lesson appears to rely too heavily on generic filler language."
    );
  }
}


/*
 * ------------------------------------------------------------
 * SECTION 9
 * EXAM STYLE
 * ------------------------------------------------------------
 */

function checkExamStyle(
  generated,
  errors,
  warnings
) {
  if (!isObject(generated.lesson)) {
    return;
  }

  const combined =
    LESSON_FIELDS
      .map(field =>
        generated.lesson[field] || ""
      )
      .join("\n")
      .toLowerCase();

  let count = 0;

  for (const phrase of EXAM_STYLE_PHRASES) {
    if (
      combined.includes(
        phrase.toLowerCase()
      )
    ) {
      count++;
    }
  }

  if (count > 0) {
    addError(
      errors,
      "Exam-oriented language detected. Constitution 365 is not an exam-notes course."
    );
  }
}


