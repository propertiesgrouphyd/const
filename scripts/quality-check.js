/*
 * ------------------------------------------------------------
 * HELPER FUNCTIONS
 * ------------------------------------------------------------
 */

function isObject(value) {
  return (
    value !== null &&
    typeof value === "object" &&
    !Array.isArray(value)
  );
}


function normalize(text) {
  if (typeof text !== "string") {
    return "";
  }

  return text
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();
}


function countOccurrences(text, phrase) {
  if (
    typeof text !== "string" ||
    !phrase
  ) {
    return 0;
  }

  const source = text.toLowerCase();
  const target = phrase.toLowerCase();

  let count = 0;
  let position = 0;

  while (true) {
    const index =
      source.indexOf(target, position);

    if (index === -1) {
      break;
    }

    count++;

    position =
      index + target.length;
  }

  return count;
}


function countTeluguCharacters(text) {
  if (typeof text !== "string") {
    return 0;
  }

  const matches =
    text.match(/[\u0C00-\u0C7F]/gu);

  return matches
    ? matches.length
    : 0;
}


function countLetterCharacters(text) {
  if (typeof text !== "string") {
    return 0;
  }

  const matches =
    text.match(/[A-Za-z\u0C00-\u0C7F]/gu);

  return matches
    ? matches.length
    : 0;
}


function teluguRatio(text) {
  const total =
    countLetterCharacters(text);

  if (total === 0) {
    return 0;
  }

  return (
    countTeluguCharacters(text) /
    total
  );
}


function splitSentences(text) {
  if (typeof text !== "string") {
    return [];
  }

  return text
    .split(/[.!?।!?]+/u)
    .map(item => normalize(item))
    .filter(Boolean);
}


function getDuplicateSentences(text) {
  const sentences =
    splitSentences(text);

  const counts = new Map();

  for (const sentence of sentences) {
    counts.set(
      sentence,
      (counts.get(sentence) || 0) + 1
    );
  }

  return [...counts.entries()]
    .filter(
      ([, count]) =>
        count > MAX_REPEATED_SENTENCE_COUNT
    )
    .map(
      ([sentence, count]) => ({
        sentence,
        count
      })
    );
}


function countParagraphs(text) {
  if (typeof text !== "string") {
    return 0;
  }

  return text
    .split(/\n\s*\n/u)
    .map(item => item.trim())
    .filter(Boolean)
    .length;
}


function countEnglishWords(text) {
  if (typeof text !== "string") {
    return 0;
  }

  const matches =
    text.match(/\b[A-Za-z]{2,}\b/g);

  return matches
    ? matches.length
    : 0;
}


function addError(errors, message) {
  errors.push(message);
}


function addWarning(warnings, message) {
  warnings.push(message);
}


/*
 * ------------------------------------------------------------
 * SECTION 1
 * BASIC LESSON CHECK
 * ------------------------------------------------------------
 */

function checkLessonStructure(
  generated,
  errors,
  warnings
) {
  if (!isObject(generated.lesson)) {
    addError(
      errors,
      "lesson is missing or is not an object."
    );

    return;
  }

  for (const field of LESSON_FIELDS) {
    const value =
      generated.lesson[field];

    if (
      typeof value !== "string" ||
      !value.trim()
    ) {
      addError(
        errors,
        `lesson.${field} is empty.`
      );

      continue;
    }

    const length =
      value.trim().length;

    const minimum =
      MIN_FIELD_CHARACTERS[field] || 40;

    if (length < minimum) {
      addError(
        errors,
        `lesson.${field} is too short (${length} characters; minimum ${minimum}).`
      );
    }

    if (countParagraphs(value) === 0) {
      addWarning(
        warnings,
        `lesson.${field} has no paragraph separation.`
      );
    }
  }
}


/*
 * ------------------------------------------------------------
 * SECTION 2
 * TOTAL CONTENT DEPTH
 * ------------------------------------------------------------
 */

function checkOverallLength(
  generated,
  errors,
  warnings
) {
  if (!isObject(generated.lesson)) {
    return;
  }

  const total =
    LESSON_FIELDS.reduce(
      (sum, field) =>
        sum +
        (
          typeof generated.lesson[field] === "string"
            ? generated.lesson[field].trim().length
            : 0
        ),
      0
    );

  if (total < MIN_TOTAL_CHARACTERS) {
    addError(
      errors,
      `Lesson is too short overall (${total} characters; minimum ${MIN_TOTAL_CHARACTERS}).`
    );
  }

  if (total > MAX_TOTAL_CHARACTERS) {
    addWarning(
      warnings,
      `Lesson is unusually long (${total} characters).`
    );
  }
}


/*
 * ------------------------------------------------------------
 * SECTION 3
 * TELUGU QUALITY
 * ------------------------------------------------------------
 */

function checkTelugu(
  generated,
  errors,
  warnings
) {
  if (!isObject(generated.lesson)) {
    return;
  }

  const combined =
    LESSON_FIELDS
      .map(field =>
        generated.lesson[field] || ""
      )
      .join("\n");

  const ratio =
    teluguRatio(combined);

  if (ratio < MIN_TELUGU_RATIO) {
    addError(
      errors,
      `Telugu character ratio is too low (${(ratio * 100).toFixed(1)}%).`
    );
  }

  const englishWords =
    countEnglishWords(combined);

  /*
   * English terminology is not automatically wrong.
   * We only warn when there is an unusually high amount.
   */

  if (englishWords > 35) {
    addWarning(
      warnings,
      `Lesson contains many English words (${englishWords}).`
    );
  }

  /*
   * Detect obvious translation-like constructions.
   */

  const translationPatterns = [
    "ఇది అంటే ఏమిటంటే",
    "దీనిని ఇలా నిర్వచించవచ్చు",
    "ఈ సందర్భంలో",
    "పై విధంగా",
    "క్రింది విధంగా"
  ];

  let translationPatternCount = 0;

  for (const phrase of translationPatterns) {
    translationPatternCount +=
      countOccurrences(
        combined,
        phrase
      );
  }

  if (translationPatternCount >= 5) {
    addWarning(
      warnings,
      "Repeated formal/translation-like Telugu constructions detected."
    );
  }
}


